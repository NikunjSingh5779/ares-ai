"""Agent monitoring and improvement API router.

Endpoints:
    GET /api/v1/agents/status — Pipeline status and agent outputs from last run
    GET /api/v1/agents/improvements — List recent improvement records
    POST /api/v1/agents/improvements/apply — Apply an improvement suggestion
    GET /api/v1/agents/improvements/metrics — Get aggregate metrics summary
"""

from __future__ import annotations

import logging
from typing import Annotated, Any

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.ext.asyncio import AsyncSession

from backend.core.dependencies import get_db
from backend.routers.analysis import get_last_state
from backend.services import improvement_service

logger = logging.getLogger("ares.api.agents")

router = APIRouter(prefix="/api/v1/agents", tags=["agents"])

_STORE_ERROR = "Improvement history unavailable"


@router.get("/status")
async def agent_status() -> dict[str, Any]:
    """Get pipeline execution status from the last run.

    Returns current_node, completed/failed/skipped agent lists,
    model chain used for each agent, and degradation status.
    """
    state = get_last_state()
    if state is None:
        return {
            "pipeline_status": {
                "current_node": "",
                "completed_nodes": [],
                "failed_nodes": [],
                "skipped_nodes": [],
            },
            "model_chain_used": {},
            "degraded": False,
            "total_latency_ms": 0,
            "has_run": False,
        }

    state_dict = state.model_dump() if hasattr(state, "model_dump") else {}
    if not state_dict and hasattr(state, "__dict__"):
        state_dict = {k: v for k, v in state.__dict__.items() if not k.startswith("_")}
        # Handle Pydantic models inside state
        for k, v in state_dict.items():
            if hasattr(v, "model_dump"):
                state_dict[k] = v.model_dump()

    return {
        **state_dict,
        "has_run": True,
    }


@router.get("/improvements")
async def list_improvements(
    limit: Annotated[int, Query(ge=1, le=100, description="Maximum records to return")] = 20,
    db: AsyncSession = Depends(get_db),
) -> list[dict[str, Any]]:
    """List recent improvement records generated by the StrategyImprovementEngine.

    Args:
        limit: Maximum number of records to return (default 20, max 100).
    """
    try:
        return await improvement_service.list_records(db, limit)
    except Exception as exc:  # noqa: BLE001 - stable 503 for the dashboard
        logger.error("Could not list improvement records", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=_STORE_ERROR,
        ) from exc


@router.post("/improvements/apply")
async def apply_improvement(
    body: dict[str, Any],
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """Mark an improvement suggestion as applied.

    Request body::

        {"record_id": "3f1c0f9e-..."}
    """
    record_id = body.get("record_id", "")
    if not record_id:
        raise HTTPException(status_code=400, detail="record_id is required")

    try:
        success = await improvement_service.apply_record(db, str(record_id))
    except Exception as exc:  # noqa: BLE001
        logger.error("Could not apply improvement record", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=_STORE_ERROR,
        ) from exc
    if not success:
        raise HTTPException(
            status_code=404,
            detail=f"Improvement record '{record_id}' not found",
        )
    return {"success": True, "record_id": record_id}


@router.get("/improvements/metrics")
async def improvement_metrics(
    db: AsyncSession = Depends(get_db),
) -> dict[str, float]:
    """Get aggregate improvement metrics summary.

    Returns avg_confidence_accuracy, execution_rate, error_rate, total_runs.
    """
    try:
        return await improvement_service.metrics(db)
    except Exception as exc:  # noqa: BLE001
        logger.error("Could not compute improvement metrics", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=_STORE_ERROR,
        ) from exc
